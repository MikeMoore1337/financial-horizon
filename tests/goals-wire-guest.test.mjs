import test from 'node:test';
import assert from 'node:assert/strict';
import {createSampleState,validateState} from '../finance.js';
import {encryptBackup,decryptBackup} from '../backup.js';
import {addGuestBankAccount} from '../src/importers/bank-statements/guest-ledger.js';
import {applyGuestGoalCommand,projectGuestGoals,assertGuestGoalRestore} from '../src/domain/goals/guest.mjs';
import {decodeGoalEntities,assertGoalSnapshotExtends} from '../src/domain/goals/server-goals.ts';
import {verifyGoalDependencies,verifyGoalReceiptCandidate} from '../src/domain/goals/goal-command-candidate.mjs';
const id=n=>'a0000000-0000-4000-8000-'+String(n).padStart(12,'0');
const [A,G,H,C,D,E]=[1,2,3,4,5,6].map(id),on='2026-01-01';
const initial={id:C,type:'create',on,title:'Цель',category:'other',targetCents:12000000,targetDate:'2027-01-01',openingCents:1000000,monthlyCents:null,plannedFunding:'virtual'};
const goal=(events=[initial],saved=1000000,gid=G)=>({id:gid,kind:'goal',entity_revision:events.length,data:{account_id:A,event_log:events,saved_minor:saved}});
const account=(reserved=0,rev=1)=>({id:A,kind:'account',entity_revision:rev,data:{name:'Счёт',type:'cash',currency:'RUB',opening_minor:2000000,balance_minor:2000000,reserved_minor:reserved,available_minor:2000000-reserved,archived_at:null}});
const cmd=(e,versions,base=0,gid=G)=>({schema_version:2,client_mutation_id:e.id,base_revision:base,action:'goal.append',expected_entity_revisions:versions,payload:{goal_id:gid,account_id:A,event:e}});
const upsert=e=>({kind:'upsert',entity_id:e.id,entity_revision:e.entity_revision,payload:{entity:e}});
test('guest goal uses only existing local cash, survives encrypted backup and rejects destructive old restore',async()=>{
 const s=createSampleState(),old=structuredClone(s);
 addGuestBankAccount(s,{id:A,name:'Synthetic',openingMinor:2000000},s.revision);
 const original=structuredClone(s.bankStatements);
 applyGuestGoalCommand(s,cmd(initial,{[A]:s.revision+1},s.revision));
 s.revision++;
 assert.equal(projectGuestGoals(s).goals[0].savedMinor,1000000);
 assert.deepEqual(s.bankStatements,original);
 const next={id:D,type:'contribution',on,amountCents:1000001,funding:'virtual'};
 const before=structuredClone(s);
 assert.throws(()=>applyGuestGoalCommand(s,cmd(next,{[A]:s.revision+1,[G]:1},s.revision)),/средств/);
 assert.deepEqual(s,before);
 const restored=await decryptBackup(await encryptBackup(s,'synthetic goal backup phrase'),'synthetic goal backup phrase');
 assert.deepEqual(restored,s);
 assertGuestGoalRestore(s,restored);
 assert.throws(()=>assertGuestGoalRestore(s,old),/потерял цель/);
 const forged=structuredClone(s);forged.guestGoals.goals[0].data.saved_minor++;
 assert.throws(()=>validateState(forged));
});
test('wire snapshot rejects missing goal history, duplicate event IDs and mismatched shared earmarks',()=>{
 const base=[account(1000000),goal()];
 assert.equal(decodeGoalEntities(base)[0].savedMinor,1000000);
 assert.throws(()=>decodeGoalEntities([account(0),goal()]),/резерв/);
 assert.throws(()=>decodeGoalEntities([account(2000000),goal(),goal([initial],1000000,H)]),/Повтор события/);
 assert.throws(()=>assertGoalSnapshotExtends(base,[account()]),/потерял цель/);
 assert.throws(()=>assertGoalSnapshotExtends(base,[account(1000000),goal([{...initial,title:'Переписано'}])]),/История/);
 const reserve={id:H,kind:'reserve',data:{allocated_minor:1000000,allocations_by_account:[{account_id:A,allocated_minor:1000000}]}};
 assert.equal(decodeGoalEntities([account(2000000),goal(),reserve]).length,1);
 assert.throws(()=>decodeGoalEntities([account(1000000),goal(),reserve]),/резерв/);
});
test('goal create receipt must prove exact command, cash and reserved amount',()=>{
 const command=cmd(initial,{[A]:1}),before=[account()];
 verifyGoalDependencies(command,before);
 const changes=[upsert(goal()),upsert(account(1000000,2))];
 verifyGoalReceiptCandidate(command,changes,before,false);
 const forged=structuredClone(changes);
 forged[1].payload.entity.data.balance_minor--;
 assert.throws(()=>verifyGoalReceiptCandidate(command,forged,before,false),/распределение/);
 assert.throws(()=>verifyGoalReceiptCandidate(command,[changes[0]],before,false));
 const stale=structuredClone(command);stale.expected_entity_revisions[A]=2;
 assert.throws(()=>verifyGoalDependencies(stale,before),/изменился/);
 verifyGoalReceiptCandidate(command,changes,[account(1000000,2),goal()],true);
 const wrong=structuredClone(changes);wrong[0].payload.entity.data.event_log[0].title='Другой';
 assert.throws(()=>verifyGoalReceiptCandidate(command,wrong,before,false));
});
